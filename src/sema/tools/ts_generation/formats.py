"""Emit ``formats.ts``: every format in the closure as a zod schema.

A format is a dependency-free refinement of one JSON primitive, so its
schema file is the whole specification: the generator reads the format's
JSON Schema keywords and translates each to the zod call that means the
same thing. There is no per-format template. The one escape hatch is
``FORMAT_REFINEMENTS``, for a published format whose description states a
rule its keywords cannot (an arithmetic invariant on a string); the Python
runtime enforces the same rule in its validator.

``formats.test.ts`` is emitted beside it from each schema's ``examples``
and ``counterexamples``.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from sema.tools.runtime_generation.helpers import (
    load_schema_for_node,
    local_name_to_class,
)


STRING_KEYWORDS = ("minLength", "maxLength", "pattern")
NUMBER_KEYWORDS = ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum")
PRIMITIVE_BASE = {
    "string": "z.string()",
    "integer": "z.number().int()",
    "number": "z.number()",
    "boolean": "z.boolean()",
}


class FormatRefinement:
    """A rule a format's keywords cannot state, emitted as a named zod refinement."""

    def __init__(self, function_name: str, body: str, message: str) -> None:
        self.function_name = function_name
        self.body = body
        self.message = message


FORMAT_REFINEMENTS: dict[str, FormatRefinement] = {
    "market.slot.name": FormatRefinement(
        function_name="checkMarketSlotNameGrid",
        body=(
            "function checkMarketSlotNameGrid(v: string): boolean {\n"
            "    const slotStart = Number(v.slice(v.lastIndexOf('.') + 1));\n"
            "    return slotStart % 300 === 0;\n"
            "}"
        ),
        message="market.slot.name slot start must be divisible by 300",
    ),
}


def regex_literal(pattern: str) -> str:
    return "/" + pattern.replace("/", "\\/") + "/"


def zod_expression(name: str, schema: dict[str, Any]) -> str:
    """The zod chain for one format, from its JSON Schema keywords alone."""
    primitive = schema["type"]
    if primitive not in PRIMITIVE_BASE:
        raise ValueError(f"{name}: unsupported format primitive {primitive!r}")
    class_name = local_name_to_class(name)
    chain = PRIMITIVE_BASE[primitive]

    allowed = STRING_KEYWORDS if primitive == "string" else NUMBER_KEYWORDS
    unexpected = sorted(
        k
        for k in (*STRING_KEYWORDS, *NUMBER_KEYWORDS)
        if k in schema and k not in allowed
    )
    if unexpected:
        raise ValueError(f"{name}: keywords {unexpected} do not apply to {primitive}")

    if primitive == "string":
        if "minLength" in schema and schema.get("maxLength") == schema["minLength"]:
            chain += f".length({schema['minLength']})"
        else:
            if "minLength" in schema:
                chain += f".min({schema['minLength']})"
            if "maxLength" in schema:
                chain += f".max({schema['maxLength']})"
        if "pattern" in schema:
            chain += f".regex({regex_literal(schema['pattern'])}, 'Fails {class_name} format')"
    else:
        if "minimum" in schema:
            chain += f".min({schema['minimum']})"
        if "maximum" in schema:
            chain += f".max({schema['maximum']})"
        if "exclusiveMinimum" in schema:
            chain += f".gt({schema['exclusiveMinimum']})"
        if "exclusiveMaximum" in schema:
            chain += f".lt({schema['exclusiveMaximum']})"

    refinement = FORMAT_REFINEMENTS.get(name)
    if refinement is not None:
        chain += f".refine({refinement.function_name}, '{refinement.message}')"
    return chain


def render_formats_ts(formats: list[str], schemas: dict[str, dict[str, Any]]) -> str:
    formats = sorted(formats)
    blocks: list[str] = []
    for name in formats:
        schema = schemas[name]
        class_name = local_name_to_class(name)
        blocks.append(
            f"/** Sema: {schema['$id']} */\n"
            f"export const {class_name} = {zod_expression(name, schema)};"
        )
    refinement_blocks = [
        FORMAT_REFINEMENTS[name].body for name in formats if name in FORMAT_REFINEMENTS
    ]
    parts = [
        "/** Sema property formats, as zod schemas. GENERATED by sema; edit the\n"
        " *  format definitions and regenerate. */\n"
        "import { z } from 'zod';",
        "\n\n".join(blocks),
    ]
    if refinement_blocks:
        parts.append("\n\n".join(refinement_blocks))
    return "\n\n".join(parts) + "\n"


def ts_literal(value: Any) -> str:
    """A JSON scalar as a TypeScript literal; strings single-quoted."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    return json.dumps(value)


def is_integral_float(value: Any) -> bool:
    return isinstance(value, float) and value.is_integer()


def render_formats_test_ts(
    formats: list[str], schemas: dict[str, dict[str, Any]]
) -> str:
    """Vitest cases from each format's ``examples`` and ``counterexamples``.

    A counterexample written as an integral float (``1.0`` against an integer
    format) states a serialized-boundary rule: the wire text is not an integer.
    JSON.parse turns it into the integer, so it is not a counterexample the
    browser can see; such values are left out of the test and named in a
    comment.
    """
    formats = sorted(formats)
    names = ", ".join(local_name_to_class(n) for n in formats)
    blocks: list[str] = []
    for name in formats:
        schema = schemas[name]
        class_name = local_name_to_class(name)
        examples = schema.get("examples", [])
        counterexamples = schema.get("counterexamples", [])
        lines = [f"describe('{name}', () => {{"]
        if examples:
            lines.append("    it('accepts every example', () => {")
            for ex in examples:
                lines.append(
                    f"        expect({class_name}.parse({ts_literal(ex)})).toBe({ts_literal(ex)});"
                )
            lines.append("    });")
        if counterexamples:
            kept = [c for c in counterexamples if not is_integral_float(c)]
            skipped = [c for c in counterexamples if is_integral_float(c)]
            lines.append("    it('rejects every counterexample', () => {")
            for c in kept:
                lines.append(
                    f"        expect({class_name}.safeParse({ts_literal(c)}).success).toBe(false);"
                )
            for c in skipped:
                lines.append(
                    f"        // {c!r} is the integer after JSON.parse; the serialized form is not."
                )
            lines.append("    });")
        lines.append("});")
        blocks.append("\n".join(lines))
    header = (
        "/** GENERATED by sema from the format definitions' examples and\n"
        " *  counterexamples. */\n"
        "import { describe, expect, it } from 'vitest';\n"
        f"import {{ {names} }} from './formats';"
    )
    return header + "\n\n" + "\n\n".join(blocks) + "\n"


def collect_formats(dag, seed) -> tuple[list[str], dict[str, dict[str, Any]]]:
    formats: list[str] = []
    schemas: dict[str, dict[str, Any]] = {}
    for node in dag.topo_sort():
        if node[0] != "format":
            continue
        _, name, _ = node
        formats.append(name)
        schemas[name] = load_schema_for_node(node, seed)
    return formats, schemas


def generate_formats(target_root: Path, dag, seed) -> None:
    formats, schemas = collect_formats(dag, seed)
    target_root.mkdir(parents=True, exist_ok=True)
    (target_root / "formats.ts").write_text(render_formats_ts(formats, schemas))
    (target_root / "formats.test.ts").write_text(
        render_formats_test_ts(formats, schemas)
    )
